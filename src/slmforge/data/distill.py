"""Teacher-model distillation of *training* data (optional, off by default, ToS-gated).

Nothing in ``finetune`` or ``eval`` ever calls this module. Running it needs every gate
of :func:`check_gates`:

* ``enabled: true``;
* ``tos_acknowledged: true`` with ``terms_reviewed_on`` (not in the future) and
  ``acknowledged_by``: you reviewed the provider's current terms (use of outputs,
  "competing model" clauses, which also cover the model you train and publish);
* ``allow_send_data: true``: prompts leave the machine. Sending personal data out of
  Morocco falls under Law 09-08 (CNDP) and may need a declaration or authorization; PII
  is redacted (:func:`redact_pii`) before anything is sent.

slm-forge records the acknowledgment; it makes no legal determination (see
``docs/distillation-terms.md``). Every output record carries ``provenance.kind =
"distilled"`` plus the teacher id, date and request parameters, and ``reviewed = false``.
Distilled data stays subject to the provider's terms and is not covered by the repo's MIT
licence. :func:`assert_not_distilled` keeps teacher output out of eval ground truth and
judge labels.
"""

