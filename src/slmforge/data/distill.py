# --------------------------------------------------------------------------- gates


class DistillGateError(Exception):
    """A distillation opt-in is missing; nothing was sent."""


class DistillationDisabled(DistillGateError):
    """Raised when ``enabled`` is false (the shipped default)."""


class ToSNotAcknowledged(DistillGateError):
    """Raised unless tos_acknowledged and terms_reviewed_on are set."""


class DataEgressNotAllowed(DistillGateError):
    """Raised unless allow_send_data is true."""


_HOW = "see docs/distillation-terms.md"


def check_gates(cfg: DistillConfig, *, today: date | None = None) -> None:
    """Raise the first failing gate: enabled, then the ToS acknowledgment, then data egress.

    Re-checked here even though ``DistillConfig`` validates the same opt-ins, because a
    config can be built without validation (``model_construct`` / ``model_copy``).
    """
    if not cfg.enabled:
        raise DistillationDisabled(f"distillation is disabled (distill.enabled: false); {_HOW}")
    if not cfg.tos_acknowledged or cfg.terms_reviewed_on is None:
        raise ToSNotAcknowledged(
            "set tos_acknowledged: true and terms_reviewed_on: <date> after reviewing the "
            f"{cfg.provider} terms; {_HOW}"
        )
    if not (cfg.acknowledged_by or "").strip():
        raise ToSNotAcknowledged(f"set acknowledged_by: <who reviewed the {cfg.provider} terms>; {_HOW}")
    if cfg.terms_reviewed_on > (today or date.today()):
        raise ToSNotAcknowledged(f"terms_reviewed_on ({cfg.terms_reviewed_on}) is in the future")
    if not cfg.allow_send_data:
        raise DataEgressNotAllowed(
            "set allow_send_data: true to send prompts to the provider (personal data leaving Morocco "
            f"may fall under Law 09-08); {_HOW}"
        )


# --------------------------------------------------------------------------- PII

PiiKind = Literal["email", "iban", "rib", "phone", "cin"]
PII_PLACEHOLDERS: Final[Mapping[str, str]] = {
    "email": "[EMAIL]",
    "iban": "[IBAN]",
    "rib": "[RIB]",
    "phone": "[PHONE]",
    "cin": "[CIN]",
}

# Alternation order = precedence for matches starting at the same position; the scan is
# left to right, so an IBAN/RIB is consumed before a phone-like run inside it is seen.
_PII_RE: Final = re.compile(
    r"(?P<email>[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,})"
    # Moroccan IBAN: MA + 2 check digits + the 24-digit RIB, plain or in groups of four.
    r"|(?P<iban>(?<![A-Za-z0-9])MA\d{2}(?:[ -]?\d{4}){6}(?!\d))"
    # RIB: bank 3 + city 3 + account 16 + key 2 digits, plain or grouped 3-3-(4x4)-2.
    r"|(?P<rib>(?<!\d)\d{3}[ -]?\d{3}[ -]?\d{4}(?:[ -]?\d{4}){3}[ -]?\d{2}(?!\d))"
    # Phones: +212 / 00212 / 0, then 5-7 and 8 digits (plain, in pairs, or 3-3-3).
    r"|(?P<phone>(?<![\d+(])(?:\(?(?:\+|00)212\)?[ .-]?(?:\(0\)[ .-]?)?|0)[5-7]"
    r"(?:(?:[ .-]?\d{2}){4}|\d{2}[ .-]?\d{3}[ .-]?\d{3})(?!\d))"
    # CIN (carte d'identite nationale): 1-2 capital letters and 5-6 digits.
    r"|(?P<cin>(?<![A-Za-z0-9])[A-Z]{1,2}\d{5,6}(?![A-Za-z0-9]))"
)


_SPACE_FOLD: Final = str.maketrans({"\u00a0": " ", "\u202f": " ", "\u2007": " ", "\u2009": " "})


def redact_pii(text: str) -> tuple[str, list[str]]:
    """Redact Moroccan CIN, RIB, IBAN, phone numbers and emails.

    Patterns: CIN ``[A-Z]{1,2}\\d{5,6}``; RIB ``\\d{24}``; IBAN ``MA\\d{26}``; phones
    ``(\\+212|0)[5-7]\\d{8}`` (also ``00212``, and grouped in pairs or threes); emails.

    Returns the redacted text and the kind of each redaction in order of occurrence
    (never the values themselves, so the list is safe to log and count). Each match is
    replaced by a placeholder such as ``[PHONE]``; redaction is idempotent. Matching runs
    on a digit-folded copy (one char per char), so Arabic-Indic digits are caught too.
    """
    kinds: list[str] = []
    parts: list[str] = []
    last = 0
    # One char per char, so offsets stay aligned: Arabic-Indic digits and typographic spaces
    # (NBSP, NNBSP, figure and thin spaces, common in French-formatted numbers) are folded.
    for m in _PII_RE.finditer(fold_digits(text).translate(_SPACE_FOLD)):
        kind = m.lastgroup or "cin"
        kinds.append(kind)
        parts += [text[last : m.start()], PII_PLACEHOLDERS[kind]]
        last = m.end()
    parts.append(text[last:])
    return "".join(parts), kinds


